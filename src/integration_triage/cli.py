"""triage: diagnose a failing integration from a ticket and request logs."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from . import evaluate as ev
from .causes import CAUSES
from .checks import reply_problems
from .compose import customer_reply, escalation_packet, runbook_entry
from .diagnose import diagnose
from .logs import parse_jsonl
from .simulate import write_cases

DEFAULT_BASELINE = Path("evals/baseline.json")


def _diagnose(args: argparse.Namespace) -> int:
    ticket = args.ticket or (Path(args.ticket_file).read_text() if args.ticket_file else "")
    raw = sys.stdin.read() if args.logs == "-" else Path(args.logs).read_text()
    d = diagnose(parse_jsonl(raw), ticket)
    reply, packet = customer_reply(d), escalation_packet(d, ticket)
    if args.format == "json":
        print(json.dumps({
            "cause": d.cause_id, "title": CAUSES[d.cause_id].title,
            "confidence": d.confidence, "severity": d.severity, "escalate": d.escalate,
            "page_oncall": d.page_oncall, "users_affected": d.users_affected,
            "evidence": [e.request_id for e in d.evidence],
            "alternatives": dict(d.alternatives), "reply": reply,
            "reply_problems": reply_problems(reply, d)}, indent=2))
        return 0
    cause = CAUSES[d.cause_id]
    print(f"cause      : {cause.title} [{d.cause_id}]  confidence {d.confidence:.2f}")
    print(f"severity   : {d.severity}   escalate: {'yes' if d.escalate else 'no'}   "
          f"page on-call: {'YES' if d.page_oncall else 'no'}   users: {d.users_affected}")
    print(f"evidence   : {', '.join(e.request_id for e in d.evidence[:5]) or '-'}")
    if args.format in ("reply", "all"):
        print("\n--- customer reply ---\n" + reply)
    if args.format in ("packet", "all"):
        print("\n--- escalation packet ---\n" + packet)
    return 0


def _eval(args: argparse.Namespace) -> int:
    report = ev.run_eval()
    if args.json:
        print(json.dumps(report, indent=2))
    else:
        print(ev.render(report))
    base = Path(args.baseline)
    if args.update_baseline:
        base.parent.mkdir(parents=True, exist_ok=True)
        base.write_text(json.dumps({"n": report["n"], "metrics": report["metrics"]}, indent=2)
                        + "\n")
        print(f"\nwrote baseline: {base}")
        return 0
    if args.check:
        if not base.exists():
            print(f"no baseline at {base}; create one with --update-baseline", file=sys.stderr)
            return 2
        res = ev.check(json.loads(base.read_text()), report)
        print("\n" + ("PASS" if res["passed"] else "BLOCKED") + " vs baseline")
        for r in res["rows"]:
            print(f"  {r['metric']:<22} {r['baseline']:.3f} -> {r['candidate']:.3f}  "
                  f"({r['delta']:+.3f}, allowed -{r['limit']:.2f})  {r['status']}")
        return 0 if res["passed"] else 1
    return 0


def _runbooks(args: argparse.Namespace) -> int:
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    for cid in CAUSES:
        (out / f"{cid}.md").write_text(runbook_entry(cid), encoding="utf-8")
    index = ["# Runbooks", "",
             "Generated by `triage runbooks` from the cause catalog. Each entry says how to "
             "confirm the cause, what to tell the customer, and when to escalate.", ""]
    index += [f"- [{c.title}]({c.id}.md) ({c.severity}, basis: {c.source})"
              for c in CAUSES.values()]
    (out / "README.md").write_text("\n".join(index) + "\n", encoding="utf-8")
    print(f"wrote {len(CAUSES)} runbooks to {out}")
    return 0


def _simulate(args: argparse.Namespace) -> int:
    print(f"wrote {write_cases(args.out, args.seed)} cases to {args.out}")
    return 0


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="triage", description=__doc__)
    sub = p.add_subparsers(dest="cmd", required=True)

    d = sub.add_parser("diagnose", help="diagnose one incident from request logs")
    d.add_argument("--logs", required=True, help="JSONL file of request logs, or - for stdin")
    d.add_argument("--ticket", default="", help="the customer's message")
    d.add_argument("--ticket-file")
    d.add_argument("--format", choices=["summary", "reply", "packet", "all", "json"],
                   default="all")
    d.set_defaults(fn=_diagnose)

    e = sub.add_parser("eval", help="score the pipeline on the labelled cases")
    e.add_argument("--check", action="store_true", help="fail if scores drop vs the baseline")
    e.add_argument("--update-baseline", action="store_true")
    e.add_argument("--baseline", default=str(DEFAULT_BASELINE))
    e.add_argument("--json", action="store_true")
    e.set_defaults(fn=_eval)

    r = sub.add_parser("runbooks", help="write one runbook per known cause")
    r.add_argument("--out", default="docs/runbooks")
    r.set_defaults(fn=_runbooks)

    s = sub.add_parser("simulate", help="regenerate the synthetic eval cases")
    s.add_argument("--out", default="src/integration_triage/data/cases.jsonl")
    s.add_argument("--seed", type=int, default=7)
    s.set_defaults(fn=_simulate)

    args = p.parse_args(argv)
    try:
        return args.fn(args)
    except (ValueError, OSError) as exc:
        print(f"triage: error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
